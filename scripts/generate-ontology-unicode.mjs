// Unicode17 properties; Unicode license and exact upstream hashes are retained in contracts/ontology/unicode-17.
import { readFileSync, writeFileSync } from 'node:fs'
import { createHash } from 'node:crypto'
import assert from 'node:assert/strict'
const root=new URL('../',import.meta.url)
const input=readFileSync(new URL('contracts/ontology/unicode-17/DerivedCoreProperties.txt',root))
const metadata=JSON.parse(readFileSync(new URL('contracts/ontology/unicode-17/unicode-data.json',root)))
const sha=createHash('sha256').update(input).digest('hex')
assert.ok(JSON.stringify(metadata).includes(sha),'DCP hash drift')
let out='// Code generated by scripts/generate-ontology-unicode.mjs; DO NOT EDIT.\n// Unicode17 DCP SHA256 '+sha+'\n// Copyright Unicode, Inc.; see contracts/ontology/unicode-17/unicode-LICENSE.txt.\npackage ontology\n'
for(const [prop,name] of [['Cased','casedRanges'],['Case_Ignorable','caseIgnorableRanges']]) {
 const ranges=[]
 for(const line of input.toString().split('\n')) {
  const m=line.match(/^([A-F0-9]+)(?:\.\.([A-F0-9]+))?\s*;\s*(Cased|Case_Ignorable)\s*(?:#|$)/)
  if(m?.[3]===prop) ranges.push([parseInt(m[1],16),parseInt(m[2]??m[1],16)])
 }
 ranges.sort((a,b)=>a[0]-b[0]);const merged=[]
 for(const r of ranges){const last=merged.at(-1);if(last&&r[0]<=last[1]+1)last[1]=Math.max(last[1],r[1]);else merged.push(r)}
 out+='var '+name+' = [][2]rune{\n'+merged.map(([lo,hi])=>`{0x${lo.toString(16)},0x${hi.toString(16)}},`).join('\n')+'\n}\n'
}
const target=new URL('runtime/go/internal/ontology/domain/unicode_properties_generated.go',root)
if(process.argv[2]==='--check')assert.equal(readFileSync(target,'utf8').replaceAll(/\s/g,''),out.replaceAll(/\s/g,''),'generated properties drift')
else writeFileSync(target,out)
